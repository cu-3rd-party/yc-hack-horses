// Coordinates traced on the original photo previews, then normalized for Konva.
function mark(
  width: number,
  height: number,
  edge: Point[],
  muzzle: Point,
  mane: Point,
  coat: Point,
  coatValue = 'саврасая',
): Annotation {
  const point = ([x, y]: Point): Point => [x / width, y / height];
  return {
    outline: edge.map(point),
    traits: [
      { label: 'Морда', value: 'светлая', at: point(muzzle) },
      { label: 'Грива', value: 'стоячая', at: point(mane) },
      { label: 'Масть', value: coatValue, at: point(coat) },
    ],
  };
}

