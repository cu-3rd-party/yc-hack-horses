// Demo ratings belong to the bundled images, including copies saved by earlier versions.
const demoQuality = new Map([
  ['./photos/single.jpg', 'Высокое'],
  ['./photos/pair.jpg', 'Среднее'],
  ...herd.flatMap(({ id }) => [
    [`./photos/${id}-1.jpg`, 'Высокое'] as const,
    [`./photos/${id}-2.jpg`, 'Среднее'] as const,
  ]),
]);
export function photoQuality(photo: Photo) {
  return demoQuality.get(photo.source) ?? 'Без оценки';
}

export function samplePhoto(key: 'single' | 'pair'): Photo {
  return {
    id: key,
    source: './photos/' + key + '.jpg',
    name: key === 'pair' ? 'Табун у сопки.jpg' : 'В степи.jpg',
    angle: 'Профиль',
    framing: 'Общий план',
    annotation: key === 'single' ? singleMark : pairMarks[0]!,
  };
}
export function initialBook(): Notebook {
  const observations = herd.flatMap((h, index) =>
    [0, 1].map((i) => {
      const id = h.id + '-' + (i + 1);
      const name = h.name + ' — ' + (i === 0 ? 'на выпасе' : 'у склона') + '.jpg';
      const photo: Photo = {
        id,
        name,
        source: './photos/' + id + '.jpg',
        angle: i === 0 ? 'Профиль' : 'Три четверти',
        framing: i === 0 || h.id === 'luna' ? 'Общий план' : 'Крупный план',
        annotation: annotations[h.id]![i]!,
      };
      return {
        id,
        horseId: h.id as string | null,
        name,
        date: new Date(Date.UTC(2026, 8, 18 - index - i * 3, 9)).toISOString(),
        photos: [photo],
        coordinates: '47.78, 106.01',
        traits: photo.annotation.traits.map(({ label, value }) => ({ label, value })),
        confidence: 0.94,
      };
    }),
  );
  observations.push({
    id: 'unlinked',
    horseId: null,
    name: 'След на водопое',
    date: '2026-09-08T08:00:00Z',
    photos: [],
    coordinates: '47.81, 105.96',
    traits: [{ label: 'Следы', value: 'у воды' }],
    confidence: 0.65,
  });
  return {
    horses: herd.map((h) => ({ ...h })),
    observations,
    review: null,
    online: true,
    failNextSave: false,
    pending: [],
    sent: 0,
    mediaBytes: 0,
    lastSync: null,
    syncError: null,
  };
}
export function uploadedPhoto(key: string, filename: string): Photo {
  return {
    id: key,
    source: key,
    name: filename,
    angle: 'Без ракурса',
    framing: 'Без плана',
    annotation: noMarks,
  };
}
