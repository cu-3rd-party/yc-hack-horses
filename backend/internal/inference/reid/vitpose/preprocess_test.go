func TestQuantizeUint8(t *testing.T) {
	cases := []struct {
		in   float64
		want uint8
	}{
		{-1, 0}, {0, 0}, {0.4, 0}, {0.5, 1}, {0.49, 0}, {1.5, 2}, {254.4, 254}, {254.6, 255}, {300, 255},
	}
	for _, c := range cases {
		if got := quantizeUint8(c.in); got != c.want {
			t.Errorf("quantizeUint8(%v)=%d want %d", c.in, got, c.want)
		}
	}
}

func TestSampleRGB(t *testing.T) {
	// буфер 3x2 (w=3,h=2): R=G=B=(y*3+x)*10
	buf := make([]uint8, 3*2*3)
	for y := 0; y < 2; y++ {
		for x := 0; x < 3; x++ {
			v := uint8((y*3 + x) * 10)
			i := (y*3 + x) * 3
			buf[i], buf[i+1], buf[i+2] = v, v, v
		}
	}
	// целочисленная координата -> точный пиксель
	rgb := sampleRGB(buf, 3, 2, 1, 1)
	for c := 0; c < 3; c++ {
		almost(t, "identity", rgb[c], 40, 1e-9)
	}
	// билинейная середина между (0,0)=0 и (1,0)=10 по x
	rgb = sampleRGB(buf, 3, 2, 0.5, 0)
	almost(t, "bilinear", rgb[0], 5, 1e-9)
	// вне границ -> 0
	rgb = sampleRGB(buf, 3, 2, -0.001, 0)
	almost(t, "oob-left", rgb[0], 0, 1e-9)
	rgb = sampleRGB(buf, 3, 2, 0, 2.5)
	almost(t, "oob-bottom", rgb[0], 0, 1e-9)
	rgb = sampleRGB(buf, 3, 2, 2.0, 1.0)
	almost(t, "right-edge", rgb[0], 50, 1e-9) // (1*3+2)*10
	// NaN/Inf -> нулевой отсчёт (как cval в scipy), без паники на индексации
	rgb = sampleRGB(buf, 3, 2, math.NaN(), 0)
	almost(t, "nan", rgb[0], 0, 1e-9)
	rgb = sampleRGB(buf, 3, 2, math.Inf(1), 0)
	almost(t, "inf", rgb[0], 0, 1e-9)
}

// synthImage — детерминированное изображение (та же формула, что в эталонном генераторе).
func synthImage(w, h int) *image.RGBA {
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			off := img.PixOffset(x, y)
			img.Pix[off] = uint8((x*7 + y*13 + 0*29) % 256)
			img.Pix[off+1] = uint8((x*7 + y*13 + 1*29) % 256)
			img.Pix[off+2] = uint8((x*7 + y*13 + 2*29) % 256)
			img.Pix[off+3] = 255
		}
	}
	return img
}

